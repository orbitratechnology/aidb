import type {
  DataChange,
  DataChangePreview,
  Filter,
  ObjectDetails,
  ObjectName,
  PageColumn,
  ValueKind,
} from '@aidb/contracts'
import { DATA_CHANGE_LIMITS, TABLE_DATA_LIMITS } from '@aidb/contracts'
import { describeFilter } from './table-view'

/** A value as text; `null` is SQL NULL. */
export type Value = string | null

/** A row identified by its primary key: each key column's value as text, in key order. */
export type RowKey = Array<{ column: string; value: string }>

/** Values by column name. */
export type Values = Record<string, Value>

export type RowEdit = {
  key: RowKey
  /** The row as it was loaded, without cells that were cut short. */
  original: Values
  /** New values of the edited columns only. */
  values: Values
}

export type RowDelete = {
  key: RowKey
  original: Values
}

/** A row to add. Columns left out get their defaults. */
export type NewRow = {
  id: string
  values: Values
}

/** Changes made in the grid and not saved yet. Nothing here has reached the database. */
export type EditBuffer = {
  /** Edited rows, by key id. */
  edits: Record<string, RowEdit>
  /** Rows marked for deletion, by key id. */
  deletes: Record<string, RowDelete>
  inserts: NewRow[]
}

export const EMPTY_BUFFER: EditBuffer = { edits: {}, deletes: {}, inserts: [] }

/** A stable id for a row key, to look rows up across pages. */
export function keyId(key: RowKey): string {
  return JSON.stringify(key.map(({ value }) => value))
}

/** "id = 7", or "order_id = 1, product_id = 2". */
export function describeKey(key: RowKey): string {
  return key.map(({ column, value }) => `${column} = ${value}`).join(', ')
}

const OBJECT_LABELS: Record<string, string> = {
  view: 'a view',
  materialized_view: 'a materialized view',
  foreign_table: 'a foreign table',
}

/** What can be changed in an object, and why not. */
export type Editing = {
  /** Why nothing can be changed here, or `null` when rows can be added. */
  blocked: string | null
  /** Why existing rows cannot be edited or deleted, or `null` when they can. */
  rowsBlocked: string | null
  /** Primary key columns, in key order. */
  keyColumns: string[]
  /** Columns that cannot be given a value, and why. */
  readOnlyColumns: Record<string, string>
}

/**
 * What the grid may change in `details`: rows of tables only, on a connection that allows
 * writes; existing rows only when the primary key identifies them on the page.
 */
export function editing({
  details,
  columns,
  readOnly,
}: {
  details: ObjectDetails
  /** The page's columns, which are the ones the role can read. */
  columns: PageColumn[]
  readOnly: boolean
}): Editing {
  const kind = details.summary.kind
  const readOnlyColumns: Record<string, string> = {}
  for (const column of details.columns) {
    if (column.generated !== null) {
      readOnlyColumns[column.name] = 'Generated by the database.'
    } else if (column.identity === 'always') {
      readOnlyColumns[column.name] = 'Filled in by the database (identity column).'
    }
  }
  for (const column of columns) {
    if (column.kind === 'array' && !(column.name in readOnlyColumns)) {
      readOnlyColumns[column.name] = 'Arrays cannot be edited here yet.'
    }
  }
  const keyColumns = details.primaryKey?.columns ?? []
  const blocked =
    kind !== 'table' && kind !== 'partitioned_table'
      ? `Only tables can be edited here; this is ${OBJECT_LABELS[kind] ?? 'not a table'}.`
      : readOnly
        ? 'This connection is read-only. Allow writes in its settings to change rows.'
        : null
  const shown = new Set(columns.map((column) => column.name))
  const rowsBlocked =
    blocked ??
    (keyColumns.length === 0
      ? 'This table has no primary key, so aidb cannot tell its rows apart to change or delete one. You can still add rows.'
      : keyColumns.some((column) => !shown.has(column))
        ? 'Your database role cannot read the whole primary key, so rows cannot be changed or deleted.'
        : null)
  return { blocked, rowsBlocked, keyColumns, readOnlyColumns }
}

/** The rows and columns of a page, as the editing helpers need them. */
export type PageRows = { columns: PageColumn[]; rows: Array<Array<string | null>> }

/**
 * The row's primary key, or `null` when a key value is missing or was cut short (the row
 * cannot be addressed exactly then).
 */
export function rowKey(
  page: PageRows,
  row: number,
  keyColumns: string[],
  truncated: Set<string>,
): RowKey | null {
  if (keyColumns.length === 0) return null
  const values = page.rows[row]
  if (!values) return null
  const key: RowKey = []
  for (const column of keyColumns) {
    const index = page.columns.findIndex((c) => c.name === column)
    const value = index < 0 ? null : (values[index] ?? null)
    if (value === null || truncated.has(`${row}:${index}`)) return null
    key.push({ column, value })
  }
  return key
}

/** The row's values by column, leaving out cells that were cut short. */
export function rowValues(page: PageRows, row: number, truncated: Set<string>): Values {
  const values: Values = {}
  page.columns.forEach((column, index) => {
    if (!truncated.has(`${row}:${index}`)) values[column.name] = page.rows[row]?.[index] ?? null
  })
  return values
}

/** How a loaded row differs from the database until the pending changes are saved. */
export type PendingRow =
  { status: 'edited'; values: Values } | { status: 'deleted'; values: Values }

/** The pending change of the row with `key`, if any. */
export function pendingRow(buffer: EditBuffer, key: RowKey | null): PendingRow | undefined {
  if (!key) return undefined
  const id = keyId(key)
  if (buffer.deletes[id]) return { status: 'deleted', values: {} }
  const edit = buffer.edits[id]
  return edit ? { status: 'edited', values: edit.values } : undefined
}

/** Records the edited values of a row; values equal to the loaded ones are not changes. */
export function editRow(buffer: EditBuffer, key: RowKey, original: Values, next: Values) {
  const id = keyId(key)
  const values: Values = {}
  for (const [column, value] of Object.entries(next)) {
    if (!(column in original) || original[column] !== value) values[column] = value
  }
  const edits = { ...buffer.edits }
  if (Object.keys(values).length === 0) delete edits[id]
  else edits[id] = { key, original, values }
  const deletes = { ...buffer.deletes }
  delete deletes[id]
  return { ...buffer, edits, deletes }
}

/** Marks a row for deletion, dropping its edits. */
export function deleteRow(buffer: EditBuffer, key: RowKey, original: Values): EditBuffer {
  const id = keyId(key)
  const edits = { ...buffer.edits }
  delete edits[id]
  return { ...buffer, edits, deletes: { ...buffer.deletes, [id]: { key, original } } }
}

/** Undoes the edits or the deletion of a row. */
export function revertRow(buffer: EditBuffer, id: string): EditBuffer {
  const edits = { ...buffer.edits }
  const deletes = { ...buffer.deletes }
  delete edits[id]
  delete deletes[id]
  return { ...buffer, edits, deletes }
}

/** Adds or replaces a new row. */
export function putNewRow(buffer: EditBuffer, row: NewRow): EditBuffer {
  const exists = buffer.inserts.some((r) => r.id === row.id)
  return {
    ...buffer,
    inserts: exists
      ? buffer.inserts.map((r) => (r.id === row.id ? row : r))
      : [...buffer.inserts, row],
  }
}

export function removeNewRow(buffer: EditBuffer, id: string): EditBuffer {
  return { ...buffer, inserts: buffer.inserts.filter((row) => row.id !== id) }
}

export type PendingCounts = { edited: number; deleted: number; added: number; total: number }

export function pendingCounts(buffer: EditBuffer): PendingCounts {
  const edited = Object.keys(buffer.edits).length
  const deleted = Object.keys(buffer.deletes).length
  const added = buffer.inserts.length
  return { edited, deleted, added, total: edited + deleted + added }
}

/** "2 edited rows, 1 deleted, 1 new". */
export function describeCounts({ edited, deleted, added }: PendingCounts): string {
  const parts: string[] = []
  if (edited > 0) parts.push(`${edited} edited ${edited === 1 ? 'row' : 'rows'}`)
  if (deleted > 0) parts.push(`${deleted} deleted`)
  if (added > 0) parts.push(`${added} new`)
  return parts.join(', ')
}

/** Why the pending changes cannot be saved yet, or `null`. */
export function bufferProblem(buffer: EditBuffer): string | null {
  const { total } = pendingCounts(buffer)
  if (total > DATA_CHANGE_LIMITS.maxSetChanges) {
    return `Save at most ${DATA_CHANGE_LIMITS.maxSetChanges} changes at once; there are ${total}.`
  }
  if (buffer.inserts.some((row) => Object.keys(row.values).length === 0)) {
    return 'Give each new row at least one value.'
  }
  return null
}

/** Kinds whose text compares exactly with the stored value, to detect rows changed since. */
const COMPARABLE: ReadonlySet<ValueKind> = new Set([
  'boolean',
  'number',
  'text',
  'date_time',
  'uuid',
])

function keyFilters(key: RowKey): Filter[] {
  return key.map(({ column, value }) => ({ column, operator: 'equals', value }))
}

/**
 * Filters that also require `values` to still be what was loaded, as far as the filter limit
 * allows. A row changed by someone else then matches nothing, and the preview says so.
 */
function unchangedFilters(
  key: RowKey,
  values: Values,
  columns: Array<string>,
  kinds: Map<string, ValueKind>,
): Filter[] {
  const filters = keyFilters(key)
  const keyNames = new Set(key.map(({ column }) => column))
  for (const column of columns) {
    if (filters.length >= TABLE_DATA_LIMITS.maxFilters) break
    const kind = kinds.get(column)
    if (keyNames.has(column) || !(column in values) || !kind || !COMPARABLE.has(kind)) continue
    const value = values[column] ?? null
    filters.push(
      value === null ? { column, operator: 'is_null' } : { column, operator: 'equals', value },
    )
  }
  return filters
}

/**
 * The pending changes as the core takes them, in the order they run: deletions (which free
 * unique values), then edits, then new rows. Each edit and deletion is addressed by primary
 * key and checks that the values it was based on are unchanged.
 */
export function toChanges(
  buffer: EditBuffer,
  table: ObjectName,
  columns: PageColumn[],
): DataChange[] {
  const kinds = new Map(columns.map((column) => [column.name, column.kind]))
  const names = columns.map((column) => column.name)
  const deletes: DataChange[] = Object.values(buffer.deletes).map(({ key, original }) => ({
    kind: 'delete',
    table,
    filters: unchangedFilters(key, original, names, kinds),
  }))
  const updates: DataChange[] = Object.values(buffer.edits).map(({ key, original, values }) => ({
    kind: 'update',
    table,
    set: Object.entries(values).map(([column, value]) => ({ column, value })),
    filters: unchangedFilters(key, original, Object.keys(values), kinds),
  }))
  const inserts: DataChange[] = buffer.inserts.map((row) => ({
    kind: 'insert',
    table,
    columns: Object.keys(row.values),
    rows: [Object.values(row.values)],
  }))
  return [...deletes, ...updates, ...inserts]
}

/** One pending change as the review shows it, in the order of [`toChanges`]. */
export type ReviewItem =
  | { kind: 'delete'; id: string; label: string; values: Array<{ column: string; value: Value }> }
  | {
      kind: 'update'
      id: string
      label: string
      /** `before` is absent when the old value is not known (a change the assistant wrote). */
      cells: Array<{ column: string; before?: Value; after: Value }>
    }
  | {
      kind: 'insert'
      id: string
      label: string
      values: Array<{ column: string; value: Value }>
      /** Columns that get their defaults. */
      defaults: string[]
    }

export function reviewItems(buffer: EditBuffer, columns: PageColumn[]): ReviewItem[] {
  const deletes: ReviewItem[] = Object.entries(buffer.deletes).map(([id, { key, original }]) => ({
    kind: 'delete',
    id,
    label: describeKey(key),
    values: columns
      .filter((column) => column.name in original)
      .map((column) => ({ column: column.name, value: original[column.name] ?? null })),
  }))
  const updates: ReviewItem[] = Object.entries(buffer.edits).map(
    ([id, { key, original, values }]) => ({
      kind: 'update',
      id,
      label: describeKey(key),
      cells: Object.entries(values).map(([column, after]) => ({
        column,
        before: original[column],
        after,
      })),
    }),
  )
  const inserts: ReviewItem[] = buffer.inserts.map((row, index) => ({
    kind: 'insert',
    id: row.id,
    label: buffer.inserts.length === 1 ? 'New row' : `New row ${index + 1}`,
    values: Object.entries(row.values).map(([column, value]) => ({ column, value })),
    defaults: columns.map((column) => column.name).filter((name) => !(name in row.values)),
  }))
  return [...deletes, ...updates, ...inserts]
}

/**
 * Changes whose row no longer matches what was loaded: an edit or deletion addresses exactly
 * one row, so any other count means the row changed or is gone. Indexes into the changes.
 */
export function staleChanges(changes: DataChange[], preview: DataChangePreview): number[] {
  return changes.flatMap((change, index) =>
    change.kind !== 'insert' && preview.changes[index]?.rows !== 1 ? [index] : [],
  )
}

/** The change an error names ("Change 2 of 3: …"), as an index, or `null`. */
export function failedChange(message: string): number | null {
  const match = /^Change (\d+) of \d+: /.exec(message)
  return match ? Number(match[1]) - 1 : null
}

/** "public.orders where id is “7”". */
function describeTarget(change: DataChange): string {
  const table = `${change.table.schema}.${change.table.name}`
  if (change.kind === 'insert') return table
  return `${table} where ${change.filters.map(describeFilter).join(' and ')}`
}

/**
 * Changes written by the assistant, for the review: what each targets and sets. The rows they
 * match and the values as stored come from the core's preview, shown next to these.
 */
export function proposalItems(changes: DataChange[]): ReviewItem[] {
  return changes.map((change, index): ReviewItem => {
    const id = String(index)
    const label = describeTarget(change)
    switch (change.kind) {
      case 'update':
        return {
          kind: 'update',
          id,
          label,
          cells: change.set.map(({ column, value }) => ({ column, after: value })),
        }
      case 'delete':
        return { kind: 'delete', id, label, values: [] }
      case 'insert':
        return {
          kind: 'insert',
          id,
          label:
            change.rows.length === 1
              ? `${label}: 1 new row`
              : `${label}: ${change.rows.length} new rows`,
          values: [],
          defaults: [],
        }
    }
  })
}
