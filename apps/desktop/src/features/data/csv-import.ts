import type {
  Column,
  CsvImportDraft,
  CsvImportRequest,
  CsvOptions,
  ObjectDetails,
} from '@aidb/contracts'

/** Which file column fills each table column; a missing entry leaves the column to its default. */
export type Mapping = Record<string, number>

/** How rows that match an existing one are treated: added only, or updated by a key. */
export type KeyOption = { id: string; label: string; columns: string[] }

/** The select value for "add rows only". */
export const INSERT_ONLY = 'insert'

/** Why a column cannot be filled from the file, or null when it can. */
export function unmappable(column: Column): string | null {
  if (column.generated !== null) return 'Generated by the database.'
  if (column.identity === 'always') return 'Filled in by the database (identity column).'
  return null
}

/** A column every row must give a value for: not null, with nothing to fill it in. */
export function required(column: Column): boolean {
  return (
    !column.nullable &&
    column.default === null &&
    column.identity === null &&
    column.generated === null
  )
}

/** The core's suggestions, by table column, leaving out columns that cannot be filled. */
export function initialMapping(draft: CsvImportDraft, details: ObjectDetails): Mapping {
  const fillable = new Set(
    details.columns.filter((column) => unmappable(column) === null).map((column) => column.name),
  )
  const mapping: Mapping = {}
  draft.suggested.forEach((column, fileColumn) => {
    if (column !== null && fillable.has(column) && !(column in mapping)) {
      mapping[column] = fileColumn
    }
  })
  return mapping
}

/** Keys rows can be matched by: the primary key, then each unique constraint. */
export function keyOptions(details: ObjectDetails): KeyOption[] {
  const keys: KeyOption[] = []
  if (details.primaryKey) {
    keys.push({
      id: `key:${details.primaryKey.name}`,
      label: `Add, or update rows with the same ${details.primaryKey.columns.join(', ')} (primary key)`,
      columns: details.primaryKey.columns,
    })
  }
  for (const unique of details.uniqueConstraints) {
    keys.push({
      id: `key:${unique.name}`,
      label: `Add, or update rows with the same ${unique.columns.join(', ')}`,
      columns: unique.columns,
    })
  }
  return keys
}

/** What the core checks and plans, in the table's column order. */
export function importRequest(
  mapping: Mapping,
  details: ObjectDetails,
  mode: string,
): CsvImportRequest {
  const request: CsvImportRequest = {
    mapping: details.columns
      .filter((column) => column.name in mapping)
      .map((column) => ({ fileColumn: mapping[column.name] ?? 0, column: column.name })),
  }
  const key = keyOptions(details).find((option) => option.id === mode)
  if (key) request.upsertKey = key.columns
  return request
}

/** Required columns no file column fills, which the core would refuse. */
export function unfilled(mapping: Mapping, details: ObjectDetails): string[] {
  return details.columns
    .filter((column) => required(column) && !(column.name in mapping))
    .map((column) => column.name)
}

const DELIMITER_NAMES: Record<string, string> = {
  ',': 'Comma',
  ';': 'Semicolon',
  '\t': 'Tab',
  '|': 'Vertical bar',
}

/** "Comma (,)" for a delimiter. */
export function delimiterLabel(delimiter: string): string {
  const name = DELIMITER_NAMES[delimiter] ?? 'Other'
  return delimiter === '\t' ? name : `${name} (${delimiter})`
}

const ENCODING_NAMES: Record<string, string> = {
  'utf-8': 'UTF-8',
  'utf-16le': 'UTF-16 LE',
  'utf-16be': 'UTF-16 BE',
  'windows-1252': 'Western (Windows-1252)',
  'iso-8859-2': 'Central European (ISO-8859-2)',
  'iso-8859-15': 'Western (ISO-8859-15)',
  shift_jis: 'Japanese (Shift_JIS)',
  'euc-kr': 'Korean (EUC-KR)',
  gbk: 'Chinese (GBK)',
}

export function encodingLabel(encoding: string): string {
  return ENCODING_NAMES[encoding] ?? encoding
}

/** The same reading options, so re-reading can be skipped. */
export function sameOptions(a: CsvOptions, b: CsvOptions): boolean {
  return a.encoding === b.encoding && a.delimiter === b.delimiter && a.hasHeader === b.hasHeader
}

/** "1,203 rows", for counts in sentences. */
export function rowCount(rows: number): string {
  return rows === 1 ? '1 row' : `${rows.toLocaleString()} rows`
}
